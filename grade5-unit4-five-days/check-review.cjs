'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const prefix=fs.existsSync(path.join(__dirname,'dist/review-logic.js'))?'./dist/':'./';
const Book=require(prefix+'review-logic.js');
let answer={text:'wrong'};
let r=Book.dayAttempt({}, {ok:false,draft:answer,at:'2026-11-23T01:00:00Z'});
assert.equal(r.done,true,'错误也可结束当前关卡，先继续闯关');
assert.equal(r.needsReview,true);assert.equal(r.firstIndependent,false);assert.equal(r.mastered,false);
answer.text='changed';assert.equal(r.firstSubmission.draft.text,'wrong','首次作答需深拷贝');
const original=JSON.parse(JSON.stringify(r));
r=Book.reviewAttempt(r,{ok:true,draft:{text:'set'},assisted:false,at:'2026-11-23T02:00:00Z'});
assert.equal(r.needsReview,false);assert.equal(r.mastered,true);assert(Book.collected(r),'掌握后保留历史');
assert.equal(r.firstCorrect,false);assert.equal(r.firstIndependent,false);assert.deepEqual(r.firstSubmission,original.firstSubmission);
assert.equal(r.lastReviewSubmission.draft.text,'set');
r=Book.reviewAttempt(r,{ok:false,draft:{text:'sit'},at:'2026-11-23T03:00:00Z'});
assert.equal(r.needsReview,true);assert.equal(r.mastered,false);assert.equal(r.reviewFailures,1);
let helped=Book.dayAttempt({}, {ok:true,assisted:true,draft:{text:'set'},at:'a'});
assert.equal(helped.firstCorrect,true);assert.equal(helped.firstIndependent,false);assert.equal(helped.needsReview,true);
helped=Book.reviewAttempt(helped,{ok:true,assisted:true,draft:{text:'set'},at:'b'});
assert.equal(helped.needsReview,true,'辅助作答不算独立掌握');
const legacy=Book.reviewAttempt({firstCorrect:false,done:true,needsReview:true},{ok:true,draft:{text:'set'},at:'c'});
assert.equal(legacy.firstSubmission,undefined,'不伪造旧记录的首次答案');assert(Book.collected(legacy));
assert.equal(Book.collected({helped:true,done:false}),false,'未作答时只看提示，不提前制造错题');
assert.equal(Book.reviewAttempt({firstCorrect:false,done:false},{ok:true,draft:{text:'set'},at:'d'}).done,true,'旧版已作答错题复习后同步完成状态');
assert.deepEqual(JSON.parse(JSON.stringify(r)),r,'可持久化并恢复记录');
console.log('错题流程验证通过：答错可继续、首次作答保留、复习独立答对后标记掌握、历史不删除、辅助作答不冒充掌握、旧记录兼容。');

// Skipping preserves a partial response without inventing an incorrect attempt.
const partial={fields:{0:'are going to clean'}};
let skipped=Book.skipAttempt({}, {draft:partial,at:'skip'});
partial.fields[0]='changed';assert.equal(skipped.firstSubmission.draft.fields[0],'are going to clean');
assert.equal(skipped.firstSubmission.correct,null);assert.equal(skipped.firstSubmission.skipped,true);
assert.equal(skipped.firstCorrect,undefined);assert.equal(skipped.everWrong,undefined);assert.equal(skipped.attempts,undefined);
assert.equal(skipped.needsReview,true);assert.equal(skipped.done,true);assert.equal(skipped.firstIndependent,false);
const skippedFirst=JSON.stringify(skipped.firstSubmission);
skipped=Book.reviewAttempt(skipped,{ok:true,draft:{fields:{0:'are going to clean'}},at:'review'});
assert.equal(skipped.mastered,true);assert.equal(skipped.needsReview,false);assert.equal(JSON.stringify(skipped.firstSubmission),skippedFirst);
assert.deepEqual(Book.skipAttempt(original,{draft:{text:'new'},at:'later'}).firstSubmission,original.firstSubmission);
console.log('跳过验证通过：保留部分作答，不伪造首答错误，回练更新掌握且保留历史。');
